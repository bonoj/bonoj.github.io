import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('./releases/v6.js',import.meta.url),'utf8');
test('v6 runtime is executable, HTTPS scoped, and covers navigation and forms',()=>{
 const controls=[],links=[],blocks=[];
 const make=(tag,attrs={})=>{
  const e={tagName:tag,id:'',innerText:'',name:'',disabled:false,readOnly:false,required:false,checked:false,isConnected:true,labels:[],getClientRects:()=>[{}],getAttribute:k=>attrs[k]??null,closest:()=>null,dispatchEvent:()=>true,click:()=>{e.clicked=true},matches:q=>q.split(',').some(s=>s.trim()==='input[type=password]'&&e.type==='password'||s.trim()==='input[type=hidden]'&&e.type==='hidden'||s.trim()==='input[type=file]'&&e.type==='file'||s.trim()==='input[type=checkbox]'&&e.type==='checkbox'||s.trim()==='input[type=radio]'&&e.type==='radio'||s.trim()==='input:not([type=checkbox]):not([type=radio]):not([type=file])'&&e.tagName==='INPUT'&&!['checkbox','radio','file'].includes(e.type)||s.trim()==='textarea'&&e.tagName==='TEXTAREA')};
  return Object.assign(e,attrs);
 };
 const text=make('INPUT',{type:'text',value:'',placeholder:'Name',labels:[{innerText:'Name'}]});
 const check=make('INPUT',{type:'checkbox',checked:false,labels:[{innerText:'Agree'}]});
 const select=make('SELECT',{options:[{text:'One',disabled:false},{text:'Two',disabled:false}],selectedIndex:0,labels:[{innerText:'Choice'}]});
 const link=make('A',{href:'https://example.com/next',innerText:'Next'});
 controls.push(text,check,select);links.push(link);blocks.push(make('H1',{innerText:'Fixture'}));
 const location={protocol:'https:',origin:'https://example.com',href:'https://example.com/',assign(url){this.lastNavigation=url}};
 const context={document:{readyState:'complete',title:'Fixture',forms:[],querySelectorAll:q=>q.startsWith('input,')?controls:q==='a[href]'?links:q.startsWith('h1,')?blocks:[]},location,getComputedStyle:()=>({visibility:'visible',display:'block'}),URL,Event:class{},HTMLInputElement:class{},HTMLTextAreaElement:class{},scrollY:0,scrollBy:()=>{},history:{back(){this.didBack=true},forward(){this.didForward=true}}};
 Object.defineProperty(context.HTMLInputElement.prototype,'value',{set(v){this._value=v;Object.defineProperty(this,'value',{value:v,writable:true,configurable:true});}});
 const run=vm.runInNewContext(source,context);
 const cmd=(operation,payload={})=>run({schema_version:1,operation,payload});
 assert.equal(cmd('observe').kind,'browser.observation');
 assert.equal(cmd('inspect_metadata').payload.metadata.control_count,3);
 assert.equal(cmd('extract',{extension:'inspect_metadata'}).payload.metadata.control_count,3);
 const extracted=cmd('extract',{collection:'controls',limit:8,cursor:null}).payload;
 assert.equal(extracted.total,3);
 assert.equal(extracted.next_cursor,null);
 assert.equal(cmd('fill',{ref:'c0',value:'Ada'}).payload.accepted,true);
 assert.equal(text._value,'Ada');
 assert.equal(cmd('fill',{ref:'c1',checked:true}).payload.checked,true);
 assert.equal(cmd('fill',{ref:'c2',option_ref:'o2_1'}).payload.accepted,true);
 assert.equal(select.selectedIndex,1);
 assert.equal(cmd('click',{ref:'l0',href:link.href}).payload.state,'initiated');
 assert.equal(link.clicked,true);
 assert.equal(cmd('navigate',{url:'https://example.com/next'}).payload.state,'initiated');
 assert.equal(location.lastNavigation,'https://example.com/next');
 assert.equal(cmd('navigate',{url:'https://other.com/'}).error,'observation_rejected');
 assert.equal(cmd('back').payload.state,'initiated');
 assert.equal(context.history.didBack,true);
 assert.equal(cmd('click',{ref:'l0',href:'https://example.com/changed'}).error,'target_unavailable');
 assert.equal(cmd('fill',{ref:'c0',value:'X',label:'Different'}).error,'target_unavailable');
});
