// Isolated deterministic tests of the actual Ender semantic emitter extracted from index.html.
// Run: node jit/ender-forge/semantic-test.mjs
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const source=readFileSync(new URL('./index.html',import.meta.url),'utf8');
const start=source.indexOf('const ENDER_SEMANTIC_ENABLED=');
const end=source.indexOf('function enderReset(){',start);
assert(start>=0&&end>start,'semantic emitter must exist');
const block=source.slice(start,end);
const context=vm.createContext({Math,Number,elapsed:0,ender:{x:0,y:0},ENDER_SENSE:125});
vm.runInContext(block+'\nthis.emit=enderSemanticEmit;this.stream=enderSemantic;this.enabled=()=>ENDER_SEMANTIC_ENABLED;',context);
const emit=context.emit,stream=context.stream;
assert.equal(context.enabled(),true);
emit('pickup',{kind:'worm',x:125,y:0},{resource:'mushrooms'});
assert.equal(stream.events.length,1,'radius boundary included');
emit('deposit',{kind:'bee',x:125.01,y:0},{resource:'wheat'});
assert.equal(stream.events.length,1,'outside radius excluded');
context.ender.x=125.01;
assert.equal(stream.events.length,1,'approaching later must not replay');
context.ender.x=0;
emit('deposit',{kind:'ant',x:0,y:0},{resource:'wood',quantity:1});
assert.equal(stream.events[1].seq,2);
assert.equal(stream.events[1].resource,'wood');
for(let i=0;i<100;i++)emit('attack',{x:0,y:0},{target:'scarab-worker'});
assert.equal(stream.events.length,48,'hard cap');
assert.equal(stream.events.at(-1).seq,102,'monotonic sequence');
assert.equal(stream.events[0].seq,55,'oldest evicted');
emit('invalid',{x:NaN,y:0});
assert.equal(stream.events.length,48);
assert(source.includes("enderSemanticEmit('pickup',a,{resource:a.cargo})"),'harvest wiring');
assert(source.includes("resources[a.cargo]++;enderSemanticEmit('deposit'"),'credit precedes delivery event');
assert(source.includes("sunDamage(beetle,'scorpion')"),'scorpion attribution');
assert(source.includes("sunDamage(a,'creep')"),'creep attribution');
assert(source.includes("fireScorpionDie(a,'scarab')"),'scorpion death attribution');
assert(source.includes("fireScorpionDie(a,'creep-contact')"),'creep contact attribution');
assert(source.includes("semantic:{schema:'ender-local-events/v1'"),'diary export');
const off=vm.createContext({Math,Number,elapsed:0,ender:{x:0,y:0},ENDER_SENSE:125});
vm.runInContext(block.replace('ENDER_SEMANTIC_ENABLED=true','ENDER_SEMANTIC_ENABLED=false')+'\nthis.emit=enderSemanticEmit;this.stream=enderSemantic;',off);
off.emit('pickup',{kind:'worm',x:0,y:0},{resource:'mushrooms'});
assert.equal(off.stream.events.length,0,'disabled mode');
console.log('Ender semantic telemetry: 17 deterministic checks passed');
